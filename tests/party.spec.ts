test('slow loading reveals the complete scene once without replacement lettering', async ({ page }, testInfo) => {
  let releaseChunk!: () => void
  let releaseFont!: () => void
  let fontRequested!: () => void
  const chunkGate = new Promise<void>((resolve) => { releaseChunk = resolve })
  const fontGate = new Promise<void>((resolve) => { releaseFont = resolve })
  const fontRequest = new Promise<void>((resolve) => { fontRequested = resolve })
  await page.route('**/assets/HeroScene-*.js', async (route) => {
    await chunkGate
    await route.continue()
  })
  await page.route('**/balloon-font.json', async (route) => {
    fontRequested()
    await fontGate
    await route.continue()
  })
  try {
    await page.goto('/', { waitUntil: 'domcontentloaded' })
    const slot = page.locator('.scene-wrap')
    await expect(slot).toBeVisible()
    await expect(slot).toHaveText('')
    await expect(page.locator('.scene-loading, .atlas-fallback')).toHaveCount(0)
    await page.evaluate(() => document.fonts.ready)
    const before = await slot.boundingBox()
    releaseChunk()
    await fontRequest
    await expect(page.locator('.hero-canvas')).toBeHidden()
    await expect(slot).toHaveText('')
    await expect(page.getByRole('button', { name: 'Replay balloon inflation' })).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath('loading-without-placeholder.png') })
    releaseFont()
    await expect(page.locator('.hero-scene.is-ready')).toBeVisible()
    await expect(page.locator('.hero-canvas')).toBeVisible()
    await expect(page.locator('.atlas-fallback')).toHaveCount(0)
    const after = await slot.boundingBox()
    expect(after!.height).toBe(before!.height)
    expect(after!.y).toBe(before!.y)
    await expect(page.locator('.hero-canvas')).toHaveAttribute('data-inflation', '100,100,100,100,100')
  } finally {
    releaseChunk()
    releaseFont()
  }
})

