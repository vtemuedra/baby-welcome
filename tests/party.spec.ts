test('a failed save keeps the note and lets the guest retry', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Leave a little love', exact: true }).click()
  await page.getByLabel('Your name', { exact: true }).fill('Retry Guest')
  await page.getByLabel('Your little love note').fill('This little note should never disappear on a failed save.')
  await page.route('**/api/messages', (route) => route.request().method() === 'POST' ? route.abort() : route.continue())
  await page.getByRole('button', { name: 'Send a little love', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText("Can't reach")
  await expect(page.getByLabel('Your little love note')).toHaveValue('This little note should never disappear on a failed save.')
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Leave a little love', exact: true }).click()
  await expect(page.getByLabel('Your name', { exact: true })).toHaveValue('Retry Guest')
  await page.unroute('**/api/messages')
  await page.getByRole('button', { name: 'Send a little love', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('Retry Guest', { exact: true })).toBeVisible()
})

