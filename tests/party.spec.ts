      gl.readPixels(0, 0, canvas.width, canvas.height, gl.RGBA, gl.UNSIGNED_BYTE, pixels)
      let colored = 0
      for (let offset = 3; offset < pixels.length; offset += 4) if (pixels[offset] > 100) colored++
