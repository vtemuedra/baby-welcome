    const scene = await page.locator('.scene-wrap').boundingBox()
    expect(title!.y).toBeGreaterThanOrEqual(scene!.y + scene!.height - 10)
    expect(await page.locator('.party-ribbon').evaluate((element) => element.getBoundingClientRect().bottom)).toBeLessThan(viewport.height)
