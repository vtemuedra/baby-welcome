test('letters pop in a fresh random order, become foil balloons, and replay', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.locator('.hero-scene.is-ready')).toBeVisible()
  const initialOrder = await page.locator('.hero-canvas').getAttribute('data-pop-order')
  expect(initialOrder).not.toBe('0,1,2,3,4')
  expect(initialOrder).not.toBe('4,3,2,1,0')
  const replay = page.getByRole('button', { name: 'Replay balloon inflation' })
  await page.evaluate(() => Object.defineProperty(document, 'hidden', { configurable: true, get: () => true }))
  await replay.click()
  const replayOrder = await page.locator('.hero-canvas').getAttribute('data-pop-order')
  expect(replayOrder).not.toBe(initialOrder)
  expect(replayOrder).not.toBe('0,1,2,3,4')
  expect(replayOrder).not.toBe('4,3,2,1,0')
  const order = replayOrder!.split(',').map(Number)
  expect([...order].sort()).toEqual([0, 1, 2, 3, 4])
  await expect(page.locator('.hero-canvas')).toHaveAttribute('data-inflation', '0,0,0,0,0')
  const flat = await page.locator('.hero-scene canvas').evaluate((canvas: HTMLCanvasElement) => canvas.toDataURL())
  await page.locator('.scene-wrap').screenshot({ path: testInfo.outputPath('01-flat-letters.png') })
  await page.evaluate(() => Reflect.deleteProperty(document, 'hidden'))
  await page.waitForFunction(() => {
    const scene = document.querySelector<HTMLElement>('.hero-canvas')!
    const values = scene.dataset.inflation!.split(',').map(Number)
    const order = scene.dataset.popOrder!.split(',').map(Number)
    if (values[order[0]] >= 65 && values[order[4]] === 0) {
      Object.defineProperty(document, 'hidden', { configurable: true, get: () => true })
      return true
    }
    return false
  })
  const middle = await page.locator('.hero-canvas').getAttribute('data-inflation')
  const values = middle!.split(',').map(Number)
  expect(values[order[0]]).toBeGreaterThan(0)
  expect(values[order[4]]).toBe(0)
  for (let position = 1; position < order.length; position++) {
    expect(values[order[position - 1]]).toBeGreaterThanOrEqual(values[order[position]])
  }
  await page.locator('.scene-wrap').screenshot({ path: testInfo.outputPath('02-random-pop.png') })
  await page.evaluate(() => Reflect.deleteProperty(document, 'hidden'))
  await expect(page.locator('.hero-canvas')).toHaveAttribute('data-inflation', '100,100,100,100,100')
  await page.locator('.scene-wrap').screenshot({ path: testInfo.outputPath('03-foil-balloons.png') })
  const inflated = await page.locator('.hero-scene canvas').evaluate((canvas: HTMLCanvasElement) => canvas.toDataURL())
  expect(inflated).not.toBe(flat)
  const canvas = page.locator('.hero-scene canvas')
  const bounds = await canvas.boundingBox()
  await canvas.click({ position: { x: bounds!.width / 2, y: bounds!.height / 2 } })
  await expect(page.locator('.hero-canvas')).toHaveAttribute('data-inflation', /^100,100,\d{1,2},100,100$/)
  await page.evaluate(() => Object.defineProperty(document, 'hidden', { configurable: true, get: () => true }))
  await replay.focus()
  await page.keyboard.press('Enter')
  expect(await page.locator('.hero-canvas').getAttribute('data-pop-order')).not.toBe(replayOrder)
  await expect(page.locator('.hero-canvas')).toHaveAttribute('data-inflation', '0,0,0,0,0')
  await page.evaluate(() => Reflect.deleteProperty(document, 'hidden'))
})