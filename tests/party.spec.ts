    await expect.poll(() => page.locator('.hero-scene canvas').evaluate((canvas: HTMLCanvasElement) => canvas.toDataURL())).not.toBe(initial)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
